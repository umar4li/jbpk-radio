# Function to search YouTube ID if not already given
def resolve_youtube_id(item):
    title, artist, album, category, ytid = item
    if ytid:
        return {
            "id": ytid,
            "youtubeId": ytid,
            "title": title,
            "artist": artist,
            "album": album,
            "category": category,
            "cover": f"https://img.youtube.com/vi/{ytid}/hqdefault.jpg"
        }
    
    query = f"{title} {artist} {album} song"
    url = f"https://www.youtube.com/results?search_query={urllib.parse.quote(query)}"
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64)"})
    found_id = None
    try:
        with urllib.request.urlopen(req, timeout=6) as res:
            html = res.read().decode('utf-8', errors='ignore')
            matches = re.findall(r'"videoId":"([a-zA-Z0-9_-]{11})"', html)
            if matches:
                found_id = matches[0]
    except Exception as e:
        # Fallback to random popular Bollywood ID if network times out
        found_id = "5-n3R4Y6DYo"

    if not found_id:
        found_id = "5-n3R4Y6DYo"

    return {
        "id": found_id,
        "youtubeId": found_id,
        "title": title,
        "artist": artist,
        "album": album,
        "category": category,
        "cover": f"https://img.youtube.com/vi/{found_id}/hqdefault.jpg"
    }

print("Resolving YouTube IDs with ThreadPool...")
start_time = time.time()
with ThreadPoolExecutor(max_workers=20) as executor:
    resolved_tracks = list(executor.map(resolve_youtube_id, raw_songs))

print(f"Done in {time.time() - start_time:.2f}s! Total resolved: {len(resolved_tracks)}")

